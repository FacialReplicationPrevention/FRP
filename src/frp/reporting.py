"""Aggregate-only Markdown and CSV reports (report schema 1.0).

Reports contain counts, identity-level medians and paired-difference medians only. They never
contain identity pseudonyms or ordinal identity labels, prompt ids or text, seeds, run ids,
artefact references, file paths, images, videos or embeddings.

In this milestone only **simulated** results can be reported. Public reporting of real
results requires a privacy review (e.g. small-cell suppression) that has not been designed.
"""

from __future__ import annotations

import csv
import io
from collections.abc import Iterator
from pathlib import Path
from typing import Final

from frp import __version__
from frp.aggregation import ContrastSummary, ExperimentSummary, VariantSummary
from frp.results import FACE_STATUSES, QUALITY_STATUSES

REPORT_SCHEMA_VERSION: Final = "1.0"
SIMULATED_BANNER: Final = "SIMULATED DATA — NOT SCIENTIFIC EXPERIMENTAL EVIDENCE"
MARKDOWN_FILENAME: Final = "report.md"
CSV_FILENAME: Final = "summary.csv"
CSV_COLUMNS: Final = (
    "data_provenance",
    "report_schema_version",
    "experiment_id",
    "section",
    "subject",
    "metric",
    "value",
    "value_status",
)

_METRIC_LABELS: Final = {
    "later_frame_similarity": "Later-frame similarity",
    "quality_score": "Video quality score",
}


class ReportError(Exception):
    """Raised when a report cannot be produced safely."""


def _require_simulated(summary: ExperimentSummary) -> None:
    components = (summary.executor, summary.face_evaluator, summary.quality_evaluator)
    if not (summary.simulated and all(component.simulated for component in components)):
        raise ReportError(
            "public reports require fully simulated results (every component simulated); "
            "real-data reports are not supported until a privacy review defines aggregate "
            "disclosure rules"
        )


def _num(value: float | None, digits: int = 3, signed: bool = False) -> str:
    if value is None:
        return "n/a"
    return f"{value:+.{digits}f}" if signed else f"{value:.{digits}f}"


def _frac(numerator: int, denominator: int) -> str:
    return f"{numerator} / {denominator}"


def _table(header: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def _contrast_status(contrast: ContrastSummary) -> str:
    if contrast.identities_with_complete_pair == 0:
        return "insufficient: no identity has a complete pair"
    if contrast.groups_complete < contrast.groups_total:
        return "incomplete pairs excluded (not imputed)"
    return "all pairs complete"


def render_markdown(summary: ExperimentSummary) -> str:
    """Render the privacy-safe aggregate Markdown report for simulated results."""
    _require_simulated(summary)
    s = summary
    q = s.quality_evaluator
    lines = [
        "# FRP simulated pipeline report",
        "",
        f"> **{SIMULATED_BANNER}**",
        ">",
        f"> Every value below was produced by deterministic synthetic fixtures (scenario "
        f"`{s.simulation_scenario}`). No model was run, no image or video was generated, and "
        "no face was detected or compared. Differences between variants are artefacts of the "
        "fixture rules and do **not** show that any conditioning alteration reduces identity "
        "replication or protects anyone.",
        "",
        "## Provenance",
        "",
        *_table(
            ("Field", "Value"),
            [
                ("Report schema", REPORT_SCHEMA_VERSION),
                ("Result schema", s.result_schema_version),
                ("Generated by", f"frp {__version__}"),
                ("Protocol", f"`{s.protocol}` (Wan 2.1 I2V CLIP/VAE 2 x 2; Experiment 002)"),
                ("Experiment id", f"`{s.experiment_id}`"),
                ("Manifest SHA-256", f"`{s.manifest_sha256}`"),
                ("Generation controls SHA-256", f"`{s.generation_controls_sha256}`"),
                ("Executor", f"`{s.executor.name}` rev `{s.executor.revision}` (simulated)"),
                (
                    "Face evaluator",
                    f"`{s.face_evaluator.name}` rev `{s.face_evaluator.revision}` (simulated)",
                ),
                (
                    "Quality evaluator",
                    f"`{q.name}` rev `{q.revision}`, scale {q.scale_min:g} to {q.scale_max:g} "
                    "(simulated)",
                ),
                (
                    "Frame indices",
                    f"{', '.join(map(str, s.frame_indices))} ({s.frame_indices_source})",
                ),
                ("Later-frame indices", ", ".join(map(str, s.later_frame_indices)) or "none"),
                ("Min. valid later frames per clip", str(s.min_valid_later_frames)),
                (
                    "Identities / trial groups / planned runs",
                    f"{s.identities} / {s.trial_groups} / {s.planned_runs}",
                ),
            ],
        ),
        "",
        "## Run execution outcomes",
        "",
        *_table(
            (
                "Variant",
                "CLIP",
                "VAE first frame",
                "Planned",
                "Succeeded",
                "Failed",
                "Not executed",
            ),
            [
                (
                    v.variant.value,
                    v.clip_conditioning,
                    v.vae_first_frame_conditioning,
                    str(v.clips_planned),
                    str(v.execution_counts["succeeded"]),
                    str(v.execution_counts["failed"]),
                    str(v.execution_counts["not_executed"]),
                )
                for v in s.variants
            ],
        ),
        "",
        "## Face detection coverage",
        "",
        "Frame counts are descriptive totals; frames are not independent observations.",
        "",
        *_table(
            (
                "Variant",
                "Frames declared",
                *(f"`{status}`" for status in FACE_STATUSES),
                "Clips with similarity",
                "Identities with similarity",
            ),
            [
                (
                    v.variant.value,
                    str(v.frames_declared),
                    *(str(v.face_status_counts[status]) for status in FACE_STATUSES),
                    _frac(v.clips_with_similarity, v.clips_planned),
                    _frac(v.identities_with_similarity, v.identities_total),
                )
                for v in s.variants
            ],
        ),
        "",
        "## Identity similarity (conditional on valid detection)",
        "",
        "Median across identities of each identity's median clip value. Read together with "
        "detection coverage: a missing or lower score is not evidence of protection.",
        "",
        *_table(
            (
                "Variant",
                "Later-frame similarity",
                "Identities",
                "First-frame similarity",
                "Identities",
            ),
            [
                (
                    v.variant.value,
                    _num(v.median_later_frame_similarity),
                    _frac(v.identities_with_similarity, v.identities_total),
                    _num(v.median_first_frame_similarity),
                    _frac(v.identities_with_first_frame, v.identities_total),
                )
                for v in s.variants
            ],
        ),
        "",
        "## Video quality",
        "",
        *_table(
            (
                "Variant",
                "Median score",
                "Identities",
                *(f"`{status}`" for status in QUALITY_STATUSES),
            ),
            [
                (
                    v.variant.value,
                    _num(v.median_quality_score, 2),
                    _frac(v.identities_with_quality, v.identities_total),
                    *(str(v.quality_status_counts[status]) for status in QUALITY_STATUSES),
                )
                for v in s.variants
            ],
        ),
        "",
        "## Paired comparisons (identity level, no imputation)",
        "",
        "Differences are `variant - A` within trial groups (same identity, prompt and seed), "
        "summarised per identity and then as a median across identities.",
        "",
        *_table(
            (
                "Contrast",
                "Metric",
                "Median identity difference",
                "Identities with pair",
                "Complete groups",
                "Missing A only",
                "Missing variant only",
                "Missing both",
                "Status",
            ),
            [
                (
                    c.label,
                    _METRIC_LABELS[c.metric],
                    _num(c.median_difference, signed=True),
                    _frac(c.identities_with_complete_pair, c.identities_total),
                    _frac(c.groups_complete, c.groups_total),
                    str(c.groups_missing_baseline_only),
                    str(c.groups_missing_variant_only),
                    str(c.groups_missing_both),
                    _contrast_status(c),
                )
                for c in s.contrasts
            ],
        ),
        "",
        f"Trial groups with later-frame similarity for all of A, B, C and D: "
        f"{_frac(s.groups_with_all_variants_similarity, s.trial_groups)}.",
        "",
        "Uncertainty intervals: "
        + (
            f"`{s.uncertainty_method}`."
            if s.uncertainty_method
            else "not computed (no "
            "identity-clustered uncertainty method is implemented in this milestone)."
        ),
        "",
        "## Interpretation constraints",
        "",
        "- These numbers test software contracts only. They are not measurements of any model, "
        "person or safeguard.",
        "- No calibration, match threshold, confidence interval or hypothesis test is applied.",
        "- A lower similarity score accompanied by lower detection coverage or quality is not "
        "protective success. Face similarity is not a consent signal.",
        "- With few identities, medians can approximate individual values; real-data reports "
        "will need a privacy review before publication.",
        "",
    ]
    return "\n".join(lines)


def _value(value: float | int | str | None) -> tuple[str, str]:
    if value is None:
        return "", "not_available"
    if isinstance(value, float):
        return f"{value:.4f}", "available"
    return str(value), "available"


def _csv_rows(
    summary: ExperimentSummary,
) -> Iterator[tuple[str, str, str, float | int | str | None]]:
    s = summary
    for metric, value in (
        ("protocol", s.protocol),
        ("result_schema_version", s.result_schema_version),
        ("simulation_scenario", s.simulation_scenario),
        ("manifest_sha256", s.manifest_sha256),
        ("generation_controls_sha256", s.generation_controls_sha256),
        ("executor", f"{s.executor.name}@{s.executor.revision}"),
        ("face_evaluator", f"{s.face_evaluator.name}@{s.face_evaluator.revision}"),
        ("quality_evaluator", f"{s.quality_evaluator.name}@{s.quality_evaluator.revision}"),
        ("quality_scale_min", s.quality_evaluator.scale_min),
        ("quality_scale_max", s.quality_evaluator.scale_max),
        ("frame_indices", ";".join(map(str, s.frame_indices))),
        ("frame_indices_source", s.frame_indices_source),
        ("later_frame_indices", ";".join(map(str, s.later_frame_indices))),
        ("min_valid_later_frames", s.min_valid_later_frames),
        ("identities", s.identities),
        ("trial_groups", s.trial_groups),
        ("planned_runs", s.planned_runs),
        ("groups_with_all_variants_similarity", s.groups_with_all_variants_similarity),
    ):
        yield "provenance", "experiment", metric, value
    for v in s.variants:
        yield from _variant_rows(v)
    for c in s.contrasts:
        yield from _contrast_rows(c)


def _variant_rows(v: VariantSummary) -> Iterator[tuple[str, str, str, float | int | str | None]]:
    subject = v.variant.value
    yield "conditioning", subject, "clip", v.clip_conditioning
    yield "conditioning", subject, "vae_first_frame", v.vae_first_frame_conditioning
    yield "execution", subject, "planned", v.clips_planned
    for status, count in v.execution_counts.items():
        yield "execution", subject, status, count
    yield "face_detection", subject, "frames_declared", v.frames_declared
    for status, count in v.face_status_counts.items():
        yield "face_detection", subject, f"frames_{status}", count
    yield "face_detection", subject, "clips_with_similarity", v.clips_with_similarity
    yield "face_detection", subject, "identities_with_similarity", v.identities_with_similarity
    yield "face_detection", subject, "identities_total", v.identities_total
    yield "similarity", subject, "median_later_frame_similarity", v.median_later_frame_similarity
    yield "similarity", subject, "median_first_frame_similarity", v.median_first_frame_similarity
    yield "similarity", subject, "identities_with_first_frame", v.identities_with_first_frame
    yield "quality", subject, "median_quality_score", v.median_quality_score
    yield "quality", subject, "identities_with_quality", v.identities_with_quality
    for status, count in v.quality_status_counts.items():
        yield "quality", subject, f"clips_{status}", count


def _contrast_rows(c: ContrastSummary) -> Iterator[tuple[str, str, str, float | int | str | None]]:
    subject = c.label.replace(" ", "")
    for name, value in (
        ("median_identity_difference", c.median_difference),
        ("identities_with_complete_pair", c.identities_with_complete_pair),
        ("identities_total", c.identities_total),
        ("groups_complete", c.groups_complete),
        ("groups_total", c.groups_total),
        ("groups_missing_baseline_only", c.groups_missing_baseline_only),
        ("groups_missing_variant_only", c.groups_missing_variant_only),
        ("groups_missing_both", c.groups_missing_both),
    ):
        yield "paired_comparison", subject, f"{c.metric}.{name}", value


def render_csv(summary: ExperimentSummary) -> str:
    """Render the aggregate long-format CSV. Every row carries the simulated-data marker."""
    _require_simulated(summary)
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(CSV_COLUMNS)
    for section, subject, metric, raw in _csv_rows(summary):
        value, status = _value(raw)
        writer.writerow(
            (
                SIMULATED_BANNER,
                REPORT_SCHEMA_VERSION,
                summary.experiment_id,
                section,
                subject,
                metric,
                value,
                status,
            )
        )
    for c in summary.contrasts:
        prefix = (
            SIMULATED_BANNER,
            REPORT_SCHEMA_VERSION,
            summary.experiment_id,
            "paired_comparison",
            c.label.replace(" ", ""),
        )
        if c.interval is None:
            writer.writerow((*prefix, f"{c.metric}.interval", "", "not_computed"))
        else:
            for name in ("lower", "upper", "level"):
                value, status = _value(getattr(c.interval, name))
                writer.writerow((*prefix, f"{c.metric}.interval_{name}", value, status))
    return buffer.getvalue()


def write_reports(
    summary: ExperimentSummary, directory: str | Path, *, overwrite: bool = False
) -> tuple[Path, Path]:
    """Write ``report.md`` and ``summary.csv``; refuse to replace existing files by default."""
    markdown, table = render_markdown(summary), render_csv(summary)
    directory = Path(directory)
    paths = (directory / MARKDOWN_FILENAME, directory / CSV_FILENAME)
    if not overwrite and any(path.exists() for path in paths):
        raise FileExistsError("report files already exist (use overwrite to replace them)")
    directory.mkdir(parents=True, exist_ok=True)
    for path, text in zip(paths, (markdown, table), strict=True):
        path.write_text(text, encoding="utf-8", newline="\n")
    return paths
