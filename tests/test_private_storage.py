def snapshot(base: Path) -> set[str]:
    return {str(p.relative_to(base)) for p in base.rglob("*")}


def make_run_dir(root: Path, run: str = RUN) -> Path:
    for part in (root / "outputs", root / "outputs" / run):
        part.mkdir(mode=0o700, exist_ok=True)
        part.chmod(0o700)
    return root / "outputs" / run


def write_partial(res: Reservation, data: bytes = b"synthetic") -> None:
    with open(res.partial_path, "r+b") as handle:  # what the encoder does: reopen by path
        handle.write(data)


