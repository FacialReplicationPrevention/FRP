def test_withdrawal_racing_a_commit_after_the_tombstone_check_still_leaves_no_final(
    store: LocalPrivateStore, root: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    res = store.reserve(out())
    write_partial(res)
    real_link = os.link

    def link_then_tombstone(*args, **kwargs):  # type: ignore[no-untyped-def]
        real_link(*args, **kwargs)
        # The withdrawal's tombstone lands just after the commit's first check.
        ledger = root / "ledger"
        token_dir = next(ledger.iterdir())
        (token_dir / ps.WITHDRAWN_FILE).write_bytes(b"")

    monkeypatch.setattr(os, "link", link_then_tombstone)
    with pytest.raises(StorageError):
        store.commit(res)
    monkeypatch.undo()
    assert not (root / "outputs" / RUN / "attempt-01.mp4").exists()
    assert res.committed_id is None


def test_receipts_errors_and_reprs_never_contain_paths_or_names(
    store: LocalPrivateStore, root: Path
) -> None:
    res = store.reserve(out())
    seen = [repr(store), str(store), repr(res), str(res)]
    for attempt in (
        lambda: store.reserve(out()),
        lambda: store.read(REF),
        lambda: store.commit(Reservation(RUN, 9, out(n=9), root / "x", (0, 0))),
    ):
        with pytest.raises(StorageError) as caught:
            attempt()
        seen.append(str(caught.value))
        seen.append(repr(caught.value))
    for text in seen:
        assert str(root) not in text
        assert "ref-a" not in text
        assert "R0001" not in text
    token = os.listdir(root / "ledger")[0]
    assert all(token not in text for text in seen)


