def test_withdrawal_removes_every_file_of_one_identity_and_nothing_else(
    store: LocalPrivateStore, root: Path
) -> None:
    commit_one(store, RUN, 1)
    store.reserve(out(RUN, 2))  # stale partial
    commit_one(store, OTHER_RUN, 1)
    put_reference(root, "ref-a.png")
    put_reference(root, "ref-b.png")
    (root / "outputs" / RUN / "unrecorded-extra.bin").write_bytes(b"x")
    (root / "outputs" / RUN / "unrecorded-extra.bin").chmod(0o600)

    assert store.remaining([RUN], [REF]) > 0
    receipts = store.withdraw([RUN], [REF])
    assert [r.outcome for r in receipts] == ["deleted", "deleted"]
    assert not (root / "outputs" / RUN).exists()
    assert not (root / "references" / "ref-a.png").exists()
    assert (root / "outputs" / OTHER_RUN / "attempt-01.mp4").exists()
    assert (root / "references" / "ref-b.png").exists()
    assert store.remaining([RUN], [REF]) == 0
    assert store.remaining([OTHER_RUN]) > 0
    again = store.withdraw([RUN], [REF])  # idempotent after a crash or a repeat
    assert [r.outcome for r in again] == ["absent", "absent"]


