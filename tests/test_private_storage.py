def test_sticky_writable_ancestor_is_accepted_only_above_an_owned_child(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    parent = tmp_path / "sticky"
    parent.mkdir()
    child = parent / "store"
    child.mkdir(mode=0o700)
    parent.chmod(0o1777)
    assert private_root_problems(child) == []
    # The same layout with a child owned by someone else is not protected by the sticky bit.
    real_lstat = os.lstat

    def foreign_child(path, *args, **kwargs):  # type: ignore[no-untyped-def]
        info = real_lstat(path, *args, **kwargs)
        if str(path) == str(child):
            values = list(info)
            values[stat.ST_UID] = os.getuid() + 4242
            return os.stat_result(values)
        return info

    monkeypatch.setattr(os, "lstat", foreign_child)
    assert any("writable by group" in p for p in private_root_problems(child))


