def test_rollback_removes_only_the_file_this_reservation_committed(
    store: LocalPrivateStore, root: Path
) -> None:
    res = store.reserve(out())
    write_partial(res)
    store.commit(res)
    final = root / "outputs" / RUN / "attempt-01.mp4"
    store.rollback(res)
    assert not final.exists()
    assert res.committed_id is None
    # A different file at the same name is never removed by a (stale) rollback.
    res2 = store.reserve(out(n=2))
    write_partial(res2)
    store.commit(res2)
    final2 = root / "outputs" / RUN / "attempt-02.mp4"
    other = final2.with_name("other")  # created first, so it cannot reuse the old inode number
    other.write_bytes(b"another file")
    other.rename(final2)
    store.rollback(res2)
    assert final2.read_bytes() == b"another file"


