# -- durability ----------------------------------------------------------------------------------


@dataclass
class FsyncSpy:
    files: int = 0
    dirs: int = 0


def spy_fsync(monkeypatch: pytest.MonkeyPatch) -> FsyncSpy:
    spy = FsyncSpy()
    real = os.fsync

    def recording(fd: int) -> None:
        if stat.S_ISDIR(os.fstat(fd).st_mode):
            spy.dirs += 1
        else:
            spy.files += 1
        real(fd)

    monkeypatch.setattr(os, "fsync", recording)
    return spy


def test_reserve_and_commit_fsync_files_and_directory_entries(
    store: LocalPrivateStore, monkeypatch: pytest.MonkeyPatch
) -> None:
    spy = spy_fsync(monkeypatch)
    res = store.reserve(out())
    assert spy.files >= 2  # key and ledger marker (and the partial)
    assert spy.dirs >= 3  # root (key), ledger tree, run directory creations
    write_partial(res)
    files, dirs = spy.files, spy.dirs
    store.commit(res)
    assert spy.files == files + 1  # the partial's data
    assert spy.dirs >= dirs + 2  # after the link and after removing the partial


def test_withdraw_and_delete_fsync_directories(
    store: LocalPrivateStore, monkeypatch: pytest.MonkeyPatch
) -> None:
    res = store.reserve(out())
    write_partial(res)
    store.commit(res)
    spy = spy_fsync(monkeypatch)
    store.withdraw([RUN])
    assert spy.files >= 1
    assert spy.dirs >= 2


def test_fsync_failure_fails_closed_and_publishes_nothing(
    store: LocalPrivateStore, root: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    res = store.reserve(out())
