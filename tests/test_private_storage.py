# -- deletion, withdrawal and replay -------------------------------------------------------------


def commit_one(store: LocalPrivateStore, run: str = RUN, n: int = 1) -> None:
    res = store.reserve(out(run, n))
    write_partial(res)
    store.commit(res)


def test_delete_is_idempotent_and_receipts_are_content_free(
    store: LocalPrivateStore, root: Path
) -> None:
    commit_one(store)
    put_reference(root)
    first = store.delete(out())
    second = store.delete(out())
    ref_first, ref_second = store.delete(REF), store.delete(REF)
    assert [first.outcome, second.outcome] == ["deleted", "absent"]
    assert [ref_first.outcome, ref_second.outcome] == ["deleted", "absent"]
    for receipt in (first, second, ref_first):
        text = repr(receipt) + str(receipt)
        assert not any(secret in text for secret in (RUN, "ref-a", str(root)))
        assert set(vars_of(receipt)) == {"kind", "outcome", "at"}


def vars_of(obj: object) -> dict[str, object]:
    return {name: getattr(obj, name) for name in obj.__slots__}  # type: ignore[attr-defined]


