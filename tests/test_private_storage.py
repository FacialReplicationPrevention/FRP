def test_key_is_owner_only_and_a_bad_or_missing_key_fails_closed(
    store: LocalPrivateStore, root: Path
) -> None:
    store.reserve(out())
    key = root / ps.KEY_FILE
    assert stat.S_IMODE(key.stat().st_mode) == 0o600
    assert key.stat().st_size == ps.KEY_BYTES
    saved = key.read_bytes()
    key.unlink()
    assert store.problems()
    with pytest.raises(StorageError):
        store.check_reservable(out(n=2))  # must not treat a lost key as an empty ledger
    with pytest.raises(StorageError):
        store.reserve(out(n=2))
    key.write_bytes(saved[:5])
    key.chmod(0o600)
    assert store.problems()
    key.write_bytes(saved)
    key.chmod(0o644)
    assert store.problems()
    key.chmod(0o600)
    assert store.problems() == []
    with pytest.raises(StorageError):
        store.reserve(out())  # the original marker is still found with the original key


