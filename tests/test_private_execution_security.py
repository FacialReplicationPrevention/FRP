LATER = timedelta(minutes=30)


def _mutations(provider: RecordingProvider) -> dict[str, Callable[[dict[str, Any]], None]]:
    def set_(**changes: Any) -> Callable[[dict[str, Any]], None]:
        return lambda fields: fields.update(changes)

    def add_pseudonym(fields: dict[str, Any]) -> None:
        fields["reference_sha256"] = {**fields["reference_sha256"], "SYN-999": "f" * 64}

    def other_gate(fields: dict[str, Any]) -> None:
        fields["gates"] = {**fields["gates"], "licence_and_intended_use": "private-record-9999"}

    def another_run(fields: dict[str, Any]) -> None:
        fields["run_ids"] = (*fields["run_ids"], "FRP-BASELINE-SYNTHETIC-EXAMPLE-R0002")

    def other_hash(fields: dict[str, Any]) -> None:
        fields["reference_sha256"] = {k: "e" * 64 for k in fields["reference_sha256"]}

    return {
        "expiry_later": set_(expires_at=provider.expires_at + LATER),
        "expiry_earlier": set_(expires_at=provider.expires_at - LATER),
        "issued_earlier": set_(issued_at=provider.issued_at - timedelta(seconds=1)),
        "reference_digest": other_hash,
        "extra_reference": add_pseudonym,
        "gate_record": other_gate,
        "attempt_limit": set_(max_attempts_per_run=2),
        "attempt_seconds": set_(max_attempt_seconds=30.0),
        "extra_run": another_run,
        "authorisation_id": set_(authorisation_id="private-record-0002"),
    }


