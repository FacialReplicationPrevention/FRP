def test_a_fault_after_the_commit_rolls_the_committed_file_back(tmp_path: Path) -> None:
    class Interrupted(FakeRuntime):
        committed_seen = False

        def release_memory(self) -> None:
            super().release_memory()
            if any(p.name == "attempt-01.mp4" for p in self.files()):
                raise KeyboardInterrupt  # e.g. Ctrl-C while cleaning up *after* the commit

        files: Callable[[], list[Path]]

    runtime = Interrupted()
    s = Setup(tmp_path, runtime=runtime)
    runtime.files = s.files
    with pytest.raises(KeyboardInterrupt):
        s.executor.execute(s.run, 1)
    assert s.files() == []  # the committed file did not survive the interruption
    assert s.private.stale_reservations() == ()


def test_rollback_never_removes_a_file_it_did_not_commit(tmp_path: Path) -> None:
    class Interrupted(FakeRuntime):
        files: Callable[[], list[Path]]
        swapped = False

        def release_memory(self) -> None:
            super().release_memory()
            final = next((p for p in self.files() if p.name == "attempt-01.mp4"), None)
            if final is not None and not self.swapped:
                self.swapped = True
                other = final.with_name("other")
                other.write_bytes(b"someone else's file")
                other.chmod(0o600)
                other.rename(final)  # replaces the committed inode
                raise KeyboardInterrupt

    runtime = Interrupted()
    s = Setup(tmp_path, runtime=runtime)
    runtime.files = s.files
    with pytest.raises(KeyboardInterrupt):
        s.executor.execute(s.run, 1)
    assert [p.read_bytes() for p in s.files()] == [b"someone else's file"]


