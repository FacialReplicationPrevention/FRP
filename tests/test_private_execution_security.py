def late_adapter(hook: Callable[[Setup, GenerationRequest, GenerationOutput], Any]) -> type:
    """An adapter that, after upstream generation *succeeded and staged* a video, runs ``hook``.

    ``hook`` may return a replacement :class:`GenerationOutput` (an executor-visible violation).
    """

    class Late(Wan21UpstreamAdapter):
        setup: Setup

        def generate(self, request: GenerationRequest, stop: Any) -> GenerationOutput:
            output = super().generate(request, stop)
            assert self.setup.files()  # the staged partial exists: only the executor can stop it
            return hook(self.setup, request, output) or output

    return Late


def make(tmp_path: Path, hook: Callable[..., Any], **kwargs: Any) -> Setup:
    adapter_class = late_adapter(hook)
    s = Setup(tmp_path, adapter_class=adapter_class, **kwargs)
    adapter_class.setup = s
    return s


def assert_no_output_survives(s: Setup, outcome: Any, detail: str) -> None:
    assert outcome.execution.status == "failed"
    assert outcome.failure_detail == detail
    assert outcome.execution.artefact is None
    assert s.files() == []  # neither a final nor a partial MP4
    assert s.private.stale_reservations() == ()
    with pytest.raises(StorageError):  # the attempt index stays spent: no silent reuse
        s.private.check_reservable(f"{exec_base()}/{s.run.run_id}/attempt-01.mp4")


