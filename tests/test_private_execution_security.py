# -- withdrawal, restart and replay ---------------------------------------------------------------


def sub(tmp_path: Path, name: str) -> Path:
    path = tmp_path / name
    path.mkdir()
    return path


def _uri(s: Setup, attempt: int) -> str:
    return f"{exec_base()}/{s.run.run_id}/attempt-{attempt:02d}.mp4"


def test_withdrawal_then_restart_never_allows_replay(tmp_path: Path) -> None:
    first = Setup(sub(tmp_path, "first"))
    assert first.executor.execute(first.run, 1).execution.status == "succeeded"
    reference = f"private://{first.private._namespace}/references/{first.run.identity_pseudonym.lower()}.png"
    first.private.withdraw([first.run.run_id], [reference])
    assert first.files() == []

    for attempt in (1, 2, 3):  # a restarted process: new executor, new adapter, same store
        again = Setup(sub(tmp_path, f"restart-{attempt}"), reuse_store=first)
        with pytest.raises(ExecutionRefused) as excinfo:
            again.executor.execute(again.run, attempt)
        assert excinfo.value.code == "invalid_input"
        again.assert_nothing_loaded_or_generated()


def test_deleting_a_committed_output_does_not_reenable_its_attempt(tmp_path: Path) -> None:
    first = Setup(sub(tmp_path, "first"))
    assert first.executor.execute(first.run, 1).execution.status == "succeeded"
    first.private.delete(_uri(first, 1))
    assert first.files() == []
    again = Setup(sub(tmp_path, "again"), reuse_store=first)
    assert again.refusal() == "invalid_input"  # attempt 1 is spent, even though the file is gone
    again.assert_nothing_loaded_or_generated()
    assert again.executor.execute(again.run, 2).execution.status == "succeeded"


