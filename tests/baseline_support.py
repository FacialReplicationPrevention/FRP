def _meta(shape: tuple[int, ...], dtype: str = "float16") -> TensorMeta:
    return TensorMeta(shape=shape, dtype=dtype, device="cuda:0")


@dataclass
class FakeBackend:
    """Records what it is asked to do. Each ``mode`` is a deliberate failure injection."""

    live: bool = False
    mode: str = "ok"
    env_sha: str = ENV_SHA
    fail_attempts: set[int] = field(default_factory=set)
    events: list[str] = field(default_factory=list)
    requests: list[GenerationRequest] = field(default_factory=list)
    loaded_with: list[VerifiedCheckpoint] = field(default_factory=list)
    steps: int = 3

    @property
    def info(self) -> BackendInfo:
        return BackendInfo(name="fake-wan21-backend", revision="test", live=self.live)

    def check_available(self) -> None:
        self.events.append("check_available")
        if self.mode == "unavailable":
            raise BackendUnavailable

    def environment_sha256(self) -> str:
        self.events.append("environment")
        return self.env_sha

    def load(self, checkpoint: VerifiedCheckpoint) -> None:
        self.events.append("load")
        self.loaded_with.append(checkpoint)
        if self.mode == "load_error":
            raise RuntimeError("secret-path-should-not-leak")

    def generate(self, request: GenerationRequest, stop: StopSignal) -> GenerationOutput:
        self.events.append("generate")
        self.requests.append(request)
        if self.mode == "remote_call":
            import socket

            socket.getaddrinfo("example.invalid", 443)
        if self.mode == "dashscope":
            import sys
            import types

            sys.modules["dashscope"] = types.ModuleType("dashscope")
        if self.mode == "timeout":
            raise GenerationTimeout
        if self.mode == "oom":
            raise GenerationResourceExhausted
        if self.mode == "error" or request.attempt_index in self.fail_attempts:
            raise RuntimeError("secret-prompt-text-should-not-leak")
        if (reason := stop.reason()) is not None:
            raise GenerationInterrupted(reason)
        return GenerationOutput(
            artefact_uri=request.output_uri,
            video_shape=(3, request.frame_count, 480, 832),
            gpu_seconds=1.5,
            observation=self._observation(request),
        )

    def _observation(self, request: GenerationRequest) -> ConditioningObservation:
        token = request.reference.token
        clip_out = _meta((1, 257, 1280))
        y_meta = _meta((20, 3, 60, 104))
        vae_token = "ref-other" if self.mode == "vae_other_reference" else token
        calls = []
        for step in range(self.steps):
            for branch in ("positive", "negative"):
                neg_y_source = 99 if self.mode == "cfg_y_differs" and branch == "negative" else 2
                neg_clip = 98 if self.mode == "cfg_clip_differs" and branch == "negative" else 1
                calls.append(
                    CfgCallObservation(
                        step_index=step,
                        branch=branch,  # type: ignore[arg-type]
                        clip_fea=clip_out,
                        clip_fea_source=neg_clip if branch == "negative" else 1,
                        y=y_meta,
                        y_source=neg_y_source if branch == "negative" else 2,
                        context=_meta((1, 512, 4096), "bfloat16"),
                    )
                )
        if self.mode == "cfg_order":
            calls[0], calls[1] = calls[1], calls[0]
        return ConditioningObservation(
            clip_route=RouteObservation(token, clip_out, 1),
            vae_route=RouteObservation(vae_token, y_meta, 2),
            cfg_calls=tuple(calls),
        )

    def cleanup(self) -> None:
        self.events.append("cleanup")
        if self.mode == "cleanup_error":
            raise RuntimeError

    def close(self) -> None:
        self.events.append("close")


class RecordingProvider:
    """A test-only provider that grants whatever matches the request, optionally degraded."""

    def __init__(self, **overrides: Any) -> None:
        self.overrides = overrides
        self.requests: list[AuthorisationRequest] = []

    def authorise(self, request: AuthorisationRequest) -> PrivateAuthorisation | None:
        self.requests.append(request)
        fields: dict[str, Any] = {
            "authorisation_id": "private-record-0001",
            "executor_mode": request.executor_mode,
            "run_ids": (request.run_id,),
            "manifest_sha256": request.manifest_sha256,
            "generation_controls_sha256": request.generation_controls_sha256,
            "source_commit": request.source_commit,
            "checkpoint_revision": request.checkpoint_revision,
            "environment_sha256": request.environment_sha256,
            "expected_files": dict(request.expected_files),
            "gates": {gate: f"private-record-{n:04d}" for n, gate in enumerate(GATE_IDS, 1)},
            "max_attempt_seconds": 60.0,
        }
        fields.update(self.overrides)
        return PrivateAuthorisation(**fields)
