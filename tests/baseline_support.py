FILES = {"weights/a.bin": b"synthetic-a", "weights/b.bin": b"synthetic-b", "config.json": b"{}"}


def example_data() -> dict[str, Any]:
    return copy.deepcopy(yaml.safe_load(EXAMPLE_BASELINE.read_text(encoding="utf-8")))


def make_checkpoint(root: Path) -> dict[str, str]:
    """Write tiny synthetic files and return their true SHA-256 manifest."""
    for name, content in FILES.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    return {name: sha256_of_file(root / name) for name in FILES}


